# Vendor makefile generator for TECNO POVA 6 Pro 5G (LI9)
# Firmware Base:  HiOS 15.1.2.170SP05
# Firmware Build: OP001PF001AZ
#
# Written in POSIX-compatible shell syntax so it runs cleanly under both
# bash (Linux/macOS AOSP build hosts) and POSIX sh/ash environments.
# Generates vendor/tecno/li9/{Android.bp,Android.mk,BoardConfigVendor.mk,li9-vendor.mk}
# directly from proprietary-files.txt.

set -eu

DEVICE="li9"
VENDOR="tecno"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
BLOB_LIST="${SCRIPT_DIR}/proprietary-files.txt"
if [ -z "${ANDROID_ROOT:-}" ]; then
    ANDROID_ROOT="$(cd "${SCRIPT_DIR}/../../.." 2>/dev/null && pwd || echo "${SCRIPT_DIR}")"
fi
OUTPUT_DIR="${ANDROID_ROOT}/vendor/${VENDOR}/${DEVICE}"

usage() {
    cat <<EOF
Usage: $(basename "$0") [OPTIONS]

Generate vendor build files for TECNO POVA 6 Pro 5G (LI9) from proprietary-files.txt.

Options:
  -o, --output DIR   Target vendor directory (default: <ANDROID_ROOT>/vendor/tecno/li9).
  -h, --help         Show this help message.
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        -o|--output)
            [ $# -ge 2 ] || { echo "Error: $1 requires an argument." >&2; exit 2; }
            OUTPUT_DIR="$2"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Error: Unknown argument '$1'." >&2
            usage >&2
            exit 2
            ;;
    esac
done

if [ ! -f "${BLOB_LIST}" ]; then
    echo "Error: Blob list not found: ${BLOB_LIST}" >&2
    exit 1
fi

mkdir -p "${OUTPUT_DIR}"

# 1. Android.bp
cat > "${OUTPUT_DIR}/Android.bp" <<'EOF'
// Automatically generated by device/tecno/li9/setup-makefiles.sh — DO NOT EDIT

soong_namespace {
    imports: [
    ],
}
EOF

# 2. Android.mk
cat > "${OUTPUT_DIR}/Android.mk" <<'EOF'
# Automatically generated by device/tecno/li9/setup-makefiles.sh — DO NOT EDIT

LOCAL_PATH := $(call my-dir)

ifeq ($(TARGET_DEVICE),li9)

endif
EOF

# 3. BoardConfigVendor.mk
cat > "${OUTPUT_DIR}/BoardConfigVendor.mk" <<'EOF'
# Automatically generated by device/tecno/li9/setup-makefiles.sh — DO NOT EDIT
# Vendor board configuration overrides for TECNO POVA 6 Pro 5G (LI9)
EOF

# 4. li9-vendor.mk
VENDOR_MK="${OUTPUT_DIR}/${DEVICE}-vendor.mk"
cat > "${VENDOR_MK}" <<'EOF'
# Automatically generated by device/tecno/li9/setup-makefiles.sh — DO NOT EDIT
# Proprietary blobs for TECNO POVA 6 Pro 5G (LI9)
# Firmware Base:  HiOS 15.1.2.170SP05
# Firmware Build: OP001PF001AZ

PRODUCT_SOONG_NAMESPACES += \
    vendor/tecno/li9

PRODUCT_COPY_FILES += \
EOF

COUNT=0
PREV_ENTRY=""
CR="$(printf '\r')"

while IFS= read -r raw_line || [ -n "${raw_line}" ]; do
    line="${raw_line%"${CR}"}"
    line="${line%%#*}"
    while :; do
        case "${line}" in
            " "*|"	"*) line="${line#?}" ;;
            *) break ;;
        esac
    done
    while :; do
        case "${line}" in
            *" "|*"	") line="${line%?}" ;;
            *) break ;;
        esac
    done
    [ -z "${line}" ] && continue

    line="${line#-}"
    line="${line%%;*}"
    case "${line}" in
        *:*) dst_rel="${line#*:}" ;;
        *)   dst_rel="${line}" ;;
    esac

    part="${dst_rel%%/*}"
    rel="${dst_rel#*/}"
    case "${part}" in
        vendor)
            target_out="\$(TARGET_COPY_OUT_VENDOR)/${rel}"
            ;;
        vendor_dlkm)
            target_out="\$(TARGET_COPY_OUT_VENDOR_DLKM)/${rel}"
            ;;
        system_dlkm)
            target_out="\$(TARGET_COPY_OUT_SYSTEM_DLKM)/${rel}"
            ;;
        system_ext)
            target_out="\$(TARGET_COPY_OUT_SYSTEM_EXT)/${rel}"
            ;;
        odm_dlkm)
            target_out="\$(TARGET_COPY_OUT_ODM_DLKM)/${rel}"
            ;;
        product)
            target_out="\$(TARGET_COPY_OUT_PRODUCT)/${rel}"
            ;;
        *)
            target_out="\$(TARGET_COPY_OUT_SYSTEM)/${dst_rel}"
            ;;
    esac

    entry="    vendor/${VENDOR}/${DEVICE}/proprietary/${dst_rel}:${target_out}"
    if [ -n "${PREV_ENTRY}" ]; then
        printf '%s \\\n' "${PREV_ENTRY}" >> "${VENDOR_MK}"
    fi
    PREV_ENTRY="${entry}"
    COUNT=$((COUNT + 1))
done < "${BLOB_LIST}"

if [ "${COUNT}" -eq 0 ]; then
    echo "Error: No blob entries found in ${BLOB_LIST}" >&2
    exit 1
fi

printf '%s\n' "${PREV_ENTRY}" >> "${VENDOR_MK}"

echo "Generated vendor makefiles in ${OUTPUT_DIR} (${COUNT} entries)."
